# The dashboard page, gzipped into flash at build time (~93 KB -> ~26 KB) and
# served with Content-Encoding: gzip. The Tailwind stylesheet (generated by
# tailwind/build_css.sh, committed) is inlined in place of its <link>, so the
# page is styled without internet access.
HTML_FILE = Path(__file__).parent / "dashboard.html"
CSS_FILE = Path(__file__).parent / "dashboard.css"
CSS_LINK = '<link rel="stylesheet" href="dashboard.css">'


def build_page() -> bytes:
    html = HTML_FILE.read_text(encoding="utf-8")
    if html.count(CSS_LINK) != 1:
        raise EsphomeError(f"{HTML_FILE.name} must contain {CSS_LINK} exactly once")
    css = CSS_FILE.read_text(encoding="utf-8")
    return html.replace(CSS_LINK, f"<style>{css}</style>").encode("utf-8")


